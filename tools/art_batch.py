"""Owner's Midjourney batch from docs/ART_GAPS.md (GG-T492): read-only except for the two files it writes.

Expands each numbered gap's prompt (the {...} / [...] placeholders become the shared suffixes) and prints the exact
file it should be saved as. Writes docs/ART_BATCH.md (paste list + file names + classes.json follow-ups).
Run: python -I tools/art_batch.py
"""
import json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import asset_names as an

GAPS = open(os.path.join(ROOT, "docs", "ART_GAPS.md"), encoding="utf-8").read()
CHAR = ("full body character concept art, standing three-quarter view, painterly anime style, loose ink linework, soft "
        "flat shading, muted palette, isolated on plain off-white background, no text, no frame --ar 1:1 --niji 5")
BACK = ("vertical cinematic matte painting, near-photoreal concept art, atmospheric haze, volumetric backlight, one "
        "small round pale moon high in the sky, wide clear open sky in the upper third, no people, no text --ar 1:2 "
        "--style raw --no large moon, planet, giant sphere, second moon")
CLASSES = {}
p = os.path.join(ROOT, "Assets", "GridGame", "Resources", "Content", "classes.json")
d = json.load(open(p, encoding="utf-8-sig"))
for c in (d if isinstance(d, list) else next(v for v in d.values() if isinstance(v, list))):
    CLASSES[c["Id"]] = c

# bounty number -> (bounty name for file stem, base class)
BOUNTY = {12: "grimjaw-the-mauler", 13: "mother-gloam", 14: "kurogane", 15: "ashpelt", 16: "thirstmouth",
          17: "rotbark", 18: "hollowe", 19: "saint-shroud", 20: "pale-bellringer", 21: "brother-vesper",
          22: "sergeant-iron-tithe"}
BACKDROP = {23: "drowned-arks", 24: "deep-shardfall", 25: "under-the-anchors"}
BOSS = {3: "oni02", 4: "mechaarmor01", 5: "swampmistress00", 6: "cyclops02", 7: "chronomancer", 8: "ceramicknight06",
        9: "captain"}
DIRECT = {1: "hierarch", 2: "mockingecho", 31: "holdwright", 32: "holdram", 33: "holdmarksman", 34: "spireburrower",
          35: "pitlurker", 36: "spireshover", 37: "tidestrider", 38: "stormcaller", 39: "bloatdrowner",
          40: "shardcaller", 41: "crystalbrute", 42: "shardskitter", 43: "chainwarden", 44: "anchorhulk",
          45: "hookthrower", 46: "lampsnuffer", 47: "duskstalker", 48: "gloommender", 49: "duskmimic"}
rows = []
for line in GAPS.splitlines():
    m = re.match(r"\| (\d+) \|", line)
    if not m:
        continue
    n = int(m.group(1))
    ticks = re.findall(r"`([^`]*\{…\}[^`]*|[^`]*\[ … \][^`]*)`", line)
    if not ticks:
        continue
    prompt = ticks[0] if n != 47 else ticks[0]
    rows.append((n, prompt))
rows.sort()
out = ["# Midjourney batch (GG-T492)", "",
       "Generated by `python -I tools/art_batch.py` from docs/ART_GAPS.md; do not hand-edit. Paste each prompt as is. "
       "Characters use `--niji 5`; backdrops carry no niji flag. After generating, run the Studio pipeline "
       "(`GridGame.Studio/tools/remove_bg.py`, then `import_art.py`) for portraits; backdrops go in as 1536x3072 jpg. "
       "Tiles (26-30) are generated by `make_tiles.py`, not Midjourney.", ""]
fol = ["", "## classes.json / content follow-ups once the art lands", ""]
cur = None
def head(t):
    global cur
    if t != cur:
        out.extend(["", "## " + t, ""]); cur = t
for n, pr in rows:
    if n in BACKDROP:
        head("Backdrops (generate 4-6 each, save as <set>-00.jpg, -01.jpg ...)")
        s = BACKDROP[n]
        text = re.sub(r"\[ … \]", BACK, pr)
        out.append(f"{n}. Files `Assets/GridGame/Resources/Backgrounds/{s}-00.jpg` onward\n\n       {text}\n")
        continue
    text = pr.replace("{…}", CHAR)
    if n in DIRECT:
        cid = DIRECT[n]; c = CLASSES.get(cid, {})
        f = an.portrait_file(c) if c else an.of(cid)
        if c.get("Portrait") == "mannequin":
            f = an.of(cid)
            fol.append(f"- `{cid}`: delete `\"Portrait\": \"mannequin\"` in classes.json (file `{f}.png` then resolves by id).")
        head("Portraits for mannequin or copied-file classes")
        extra = ""
        if n == 47:
            extra = f"\n       Lamp-Eater bounty variant (save as `lamp-eater-00.png`): same prompt, ending `…with swallowed lanterns glowing through its ribs`."
        out.append(f"{n}. File `Assets/GridGame/Resources/Portraits/{f}.png`" + (" (replaces a byte copy of the mannequin)" if n == 2 else "") + f"\n\n       {text}{extra}\n")
        if n == 1:
            fol.append("- `dialogues.json` speaker `boss`: change `\"Portrait\": \"mannequin\"` to `\"hierarch\"`.")
    elif n in BOSS:
        head("Rule-break bosses (need a boss-portrait field or own class id before they show)")
        f = an.stem(BOSS[n]) + "-boss-00"
        out.append(f"{n}. Proposed file `Portraits/{f}.png`\n\n       {text}\n")
    elif n in BOUNTY:
        head("Bounty targets (need a bounty-portrait field before they show)")
        out.append(f"{n}. Proposed file `Portraits/{BOUNTY[n]}-00.png`\n\n       {text}\n")
    elif n == 10:
        head("Portraits for mannequin or copied-file classes")
        out.append(f"{n}. File `Assets/GridGame/Resources/Portraits/naga-egg-00.png`\n\n       {text}\n")
        fol.append("- `nagaegg`: change `\"Portrait\": \"naga\"` to `\"Portrait\": \"naga-egg\"`.")
    elif n == 11:
        head("Portraits for mannequin or copied-file classes")
        out.append(f"{n}. File `Assets/GridGame/Resources/Portraits/templar-04.png` (replaces a byte copy of templar-03; no JSON change)\n\n       {text}\n")
fol.append("- Backdrops: add `\"Backgrounds\": \"drowned-arks\"` / `deep-shardfall` / `under-the-anchors` to themes `swamp2` / `desert2` / `cave2` in campaign.json, or name the files `swamp2-00.jpg` etc.")
fol.append("- Bosses (3-9) and bounties (12-22): code or content change needed first (portrait override field); not covered here.")
open(os.path.join(ROOT, "docs", "ART_BATCH.md"), "w", encoding="utf-8", newline="\n").write("\n".join(out + fol) + "\n")
print(len(rows), "prompts")
