// Draws window.ABILITY_CADENCE (data.js, written by tools/skillhex/cadence.py): one row per hero class, a Lv 1-N strip
// marking each level that brings a new ability and each stretch longer than the gap limit with none.
(function () {
  const D = window.ABILITY_CADENCE;
  const esc = s => String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
  const rows = document.getElementById('rows');
  const only = document.getElementById('only');
  const flagged = D.Classes.filter(c => c.Gaps.length).length;
  document.getElementById('sub').textContent =
    `Each hero class from its Start path to Lv ${D.MaxLevel}, 1 SP a level, spending the way the board bot does ` +
    `(best value per planner cost, cheapest route, pass-through ability weight ${D.Costs.PassThrough}). ` +
    `Lv 1 is the Start path. A stretch of more than ${D.GapLimit} levels with no new ability is flagged: ` +
    `${flagged} of ${D.Classes.length} classes. Generated by tools/skillhex/cadence.py (seed ${D.Seed}).`;

  function row(c) {
    const lv = new Set(c.Abilities.map(a => a.Level));
    const inGap = l => c.Gaps.some(g => l > g.From && (g.Closed ? l < g.To : l <= g.To));
    let strip = '';
    for (let l = 1; l <= D.MaxLevel; l++)
      strip += `<span class="${lv.has(l) ? 'n' : ''} ${inGap(l) ? 'g' : ''}" title="Lv ${l}"></span>`;
    const byLevel = new Map();
    c.Abilities.forEach(a => byLevel.set(a.Level, (byLevel.get(a.Level) || []).concat(a)));
    let items = '';
    for (const [l, abs] of byLevel)
      items += `<li><b>Lv ${l}</b>${abs.map(a => esc(a.Name)).join(', ')}</li>`;
    const gaps = c.Gaps.map(g => `<div class="gp">Gap: Lv ${g.From} to ${g.To}${g.Closed ? '' : ' (nothing new by then)'}, ${g.Length} levels</div>`).join('');
    return `<details class="${c.Gaps.length ? 'flag' : ''}" data-gap="${c.Gaps.length}">
      <summary><span class="nm">${esc(c.Name)}</span><span class="strip" style="--n:${D.MaxLevel}">${strip}</span>
      <span class="ct">${c.Abilities.length} abilities</span></summary>
      <div class="body">${gaps}<ol>${items}</ol></div></details>`;
  }

  rows.innerHTML = D.Classes.map(row).join('');
  rows.style.display = 'grid';
  rows.style.gap = '6px';
  only.addEventListener('change', () => {
    rows.querySelectorAll('details').forEach(d => { d.hidden = only.checked && d.dataset.gap === '0'; });
  });
})();
