"""Write docs/design/skill-hexagon/skillhex.js from Assets/GridGame/Resources/Content/skillhex.json.

skillhex.json (in the game content folder) is the single source of truth for the skill hexagon board. The page draws it from
skillhex.js (`window.SKILLHEX = <json>;`) so it still opens from file:// with no fetch.
Run this after every edit to skillhex.json:  python tools/skillhex/sync.py
"""
import json
import sys
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
PAGE = REPO / "docs" / "design" / "skill-hexagon"
SRC = REPO / "Assets" / "GridGame" / "Resources" / "Content" / "skillhex.json"
OUT = PAGE / "skillhex.js"


def check(d):
    """Cheap sanity checks so a broken hand edit fails here, not as a blank page."""
    errs = []
    n = d["Radius"]
    seen = set()
    for node in d["Nodes"]:
        q, r, kind = node["Q"], node["R"], node["Kind"]
        if max(abs(q), abs(r), abs(q + r)) > n:
            errs.append(f"node {q},{r} is outside radius {n}")
        if (q, r) in seen:
            errs.append(f"node {q},{r} appears twice")
        seen.add((q, r))
        slot = (q - r) % 3 == 0
        if slot and kind == "Passive" or not slot and kind != "Passive":
            errs.append(f"node {q},{r} is {kind} but {'is' if slot else 'is not'} an ability slot")
        if kind == "Ability" and not node.get("Ability"):
            errs.append(f"node {q},{r} is Ability with no Ability id")
        if kind == "Passive" and not node.get("Stats"):
            errs.append(f"node {q},{r} is Passive with no Stats")
    expected = 3 * n * (n + 1) + 1
    if len(seen) != expected:
        errs.append(f"{len(seen)} nodes, the lattice has {expected}")
    for ab, c in Counter(x["Ability"] for x in d["Nodes"] if x["Kind"] == "Ability").items():
        if c > 1:
            errs.append(f"ability {ab} is placed {c} times")
    for h in d["Heroes"]:
        for q, r in h.get("Start", []):
            if (q, r) not in seen:
                errs.append(f"hero {h['Name']} starts on missing node {q},{r}")
    return errs


def main():
    text = SRC.read_text(encoding="utf-8")
    d = json.loads(text)
    errs = check(d)
    if errs:
        print("skillhex.json has problems:", *errs[:40], sep="\n  ")
        return 1
    OUT.write_text(
        "// Generated by tools/skillhex/sync.py from skillhex.json. Do not edit; edit skillhex.json and re-run it.\n"
        "window.SKILLHEX = " + text.strip() + ";\n",
        encoding="utf-8", newline="\n")
    kinds = Counter(x["Kind"] for x in d["Nodes"])
    status = Counter(h["Status"] for h in d["Heroes"])
    print(f"wrote {OUT}: {dict(kinds)}, heroes {dict(status)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
