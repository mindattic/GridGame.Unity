"""Regenerate docs/design/store-readiness/data.js from the tables in docs/release/StoreReadiness.md.

The .md is the source; run this after editing it so the page cannot drift:
    python tools/store_readiness_page.py
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docs" / "release" / "StoreReadiness.md"
TARGET = ROOT / "docs" / "design" / "store-readiness" / "data.js"

AREAS = {"Android (Google Play)": "Android", "iOS (App Store)": "iOS", "Shared": "Shared"}
TICKET = re.compile(r"[A-Z]+-T\d+")


def cells(line):
    return [c.strip() for c in line.strip().strip("|").split("|")]


def tables(text):
    """Yield (section heading, list of row cell lists) for every table, header and divider dropped."""
    section, rows = None, None
    for line in text.splitlines():
        if line.startswith("## "):
            section = line[3:].strip()
        if line.startswith("|"):
            if rows is None:
                rows = []
            rows.append(cells(line))
        elif rows is not None:
            yield section, rows[2:]
            rows = None
    if rows is not None:
        yield section, rows[2:]


def ids(cell):
    return [] if cell in ("", "-") else [c.strip() for c in cell.split(",")]


def build(text):
    data = {"source": "docs/release/StoreReadiness.md", "rows": [], "owner": [], "siblings": []}
    for section, rows in tables(text):
        if section in AREAS:
            for num, item, status, evidence, gap, recheck in rows:
                data["rows"].append({
                    "id": num, "area": AREAS[section], "item": item, "status": status.strip("*"),
                    "evidence": evidence, "gaps": ids(gap), "recheck": ids(recheck),
                })
        elif section == "Owner-only":
            for ticket, what, unblocks in rows:
                data["owner"].append({"ticket": ticket, "what": what, "unblocks": ids(unblocks)})
        elif section and section.startswith("Depends on sibling slices"):
            for slice_, recheck, why in rows:
                ticket = TICKET.match(slice_).group(0)
                data["siblings"].append({
                    "ticket": ticket, "name": slice_[len(ticket):].strip(), "rows": ids(recheck), "why": why,
                })
        else:
            sys.exit("Unknown table under '%s' in %s" % (section, SOURCE))
    return data


def main():
    data = build(SOURCE.read_text(encoding="utf-8"))
    body = json.dumps(data, indent=2, ensure_ascii=False)
    TARGET.write_text(
        "// Generated by tools/store_readiness_page.py from docs/release/StoreReadiness.md; do not edit by hand.\n"
        "window.StoreReadiness = " + body + ";\n",
        encoding="utf-8", newline="\n")
    print("%s: %d rows, %d owner tickets, %d sibling slices"
          % (TARGET.relative_to(ROOT), len(data["rows"]), len(data["owner"]), len(data["siblings"])))


if __name__ == "__main__":
    main()
